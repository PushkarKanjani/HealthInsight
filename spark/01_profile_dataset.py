"""
spark/01_profile_dataset.py
Phase 1 — Dataset Profiler
===========================
Inspects every Synthea CSV file without assumptions.
Outputs column names, dtypes, row counts, null counts, and 5 sample rows.
MUST be run before any transformation code is written.
"""

import os
import sys
from pathlib import Path
from dotenv import load_dotenv

load_dotenv()

# Automatically configure JAVA_HOME and HADOOP_HOME if available in standard paths
if not os.getenv("JAVA_HOME"):
    default_jdk = r"C:\Program Files\Eclipse Adoptium\jdk-17.0.20.101-hotspot"
    if os.path.exists(default_jdk):
        os.environ["JAVA_HOME"] = default_jdk
        os.environ["PATH"] = os.path.join(default_jdk, "bin") + os.pathsep + os.environ.get("PATH", "")

if not os.getenv("HADOOP_HOME"):
    default_hadoop = r"C:\hadoop"
    if os.path.exists(default_hadoop):
        os.environ["HADOOP_HOME"] = default_hadoop
        os.environ["PATH"] = os.path.join(default_hadoop, "bin") + os.pathsep + os.environ.get("PATH", "")

from pyspark.sql import SparkSession
from pyspark.sql.functions import col, count, when

DATA_DIR = os.getenv("DATA_DIR", "data/raw")

# Core files required for analytics, plus key clinical files
FILES_TO_INSPECT = [
    "patients.csv",
    "encounters.csv",
    "conditions.csv",
    "organizations.csv",
    "medications.csv",
    "procedures.csv",
    "observations.csv",
]

spark = SparkSession.builder \
    .appName("HealthInsight-DatasetProfiler") \
    .master("local[*]") \
    .config("spark.driver.memory", "4g") \
    .config("spark.sql.shuffle.partitions", "4") \
    .getOrCreate()

spark.sparkContext.setLogLevel("ERROR")

md_sections = []
md_sections.append("# HealthInsight — Dataset Dictionary")
md_sections.append("> **Generated by:** `spark/01_profile_dataset.py` (Apache Spark)")
md_sections.append("> **Dataset:** Synthea Synthetic Longitudinal Healthcare Records (100% Synthetic)")
md_sections.append("")
md_sections.append("---")
md_sections.append("")

print("\n" + "=" * 80)
print("  HealthInsight Dataset Profiler (Apache Spark)")
print("=" * 80 + "\n")

for filename in FILES_TO_INSPECT:
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        print(f"[SKIP] File not found: {path}")
        continue

    file_size_mb = os.path.getsize(path) / (1024 * 1024)
    print(f"\nProfiling {filename} ({file_size_mb:.2f} MB)...")

    df = spark.read \
        .option("header", True) \
        .option("inferSchema", True) \
        .csv(path)

    row_count = df.count()
    col_count = len(df.columns)
    print(f"  Rows: {row_count:,} | Columns: {col_count}")

    # Compute null counts efficiently
    null_exprs = [count(when(col(c).isNull(), c)).alias(c) for c in df.columns]
    null_row = df.select(null_exprs).collect()[0]

    md_sections.append(f"## Table: `{filename}`")
    md_sections.append(f"- **File Path:** `{path}`")
    md_sections.append(f"- **File Size:** {file_size_mb:.2f} MB")
    md_sections.append(f"- **Total Rows:** {row_count:,}")
    md_sections.append(f"- **Total Columns:** {col_count}")
    md_sections.append("")
    md_sections.append("### Column Schema & Null Counts")
    md_sections.append("| Column Name | Inferred Spark Type | Null Count | Null % | Notes |")
    md_sections.append("|---|---|---|---|---|")

    for col_name, dtype in df.dtypes:
        null_cnt = null_row[col_name]
        null_pct = (null_cnt / row_count * 100) if row_count > 0 else 0.0
        note = "Primary Key" if col_name.lower() == "id" else ("Foreign Key" if col_name in ["PATIENT", "ENCOUNTER", "ORGANIZATION"] else "")
        md_sections.append(f"| `{col_name}` | `{dtype}` | {null_cnt:,} | {null_pct:.1f}% | {note} |")

    md_sections.append("")
    md_sections.append("### Sample Records (Top 3)")
    sample_rows = df.limit(3).collect()
    if sample_rows:
        headers = df.columns[:8]  # Limit to first 8 columns for readability
        md_sections.append("| " + " | ".join(headers) + " |")
        md_sections.append("|" + "|".join(["---"] * len(headers)) + "|")
        for row in sample_rows:
            vals = [str(row[h]).replace("|", "/")[:30] for h in headers]
            md_sections.append("| " + " | ".join(vals) + " |")

    md_sections.append("")
    md_sections.append("---")
    md_sections.append("")

output_md_path = os.path.join("docs", "dataset_dictionary.md")
with open(output_md_path, "w", encoding="utf-8") as f:
    f.write("\n".join(md_sections))

print("\n" + "=" * 80)
print(f"PROFILING COMPLETE: Dataset dictionary written to {output_md_path}")
print("=" * 80 + "\n")

spark.stop()
