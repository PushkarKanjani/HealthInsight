"""
spark/01_profile_dataset.py
Phase 1 — Dataset Profiler
===========================
Inspects every Synthea CSV file without assumptions.
Outputs column names, dtypes, row counts, null counts, and 5 sample rows.
MUST be run before any transformation code is written.
"""

import os
import sys
from pyspark.sql import SparkSession
from dotenv import load_dotenv

load_dotenv()

DATA_DIR = os.getenv("DATA_DIR", "data/raw")

# Files to inspect — add more if additional Synthea files are present
FILES_TO_INSPECT = [
    "patients.csv",
    "encounters.csv",
    "conditions.csv",
    "organizations.csv",
    # Uncomment if present:
    # "medications.csv",
    # "procedures.csv",
    # "observations.csv",
]

spark = SparkSession.builder \
    .appName("HealthInsight-Profiler") \
    .master("local[*]") \
    .getOrCreate()

spark.sparkContext.setLogLevel("WARN")

separator = "=" * 70
report_lines = []

def log(line=""):
    print(line)
    report_lines.append(line)

for filename in FILES_TO_INSPECT:
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        log(f"[SKIP] File not found: {path}")
        continue

    log(separator)
    log(f"FILE: {filename}")
    log(f"PATH: {path}")
    log(separator)

    df = spark.read \
        .option("header", True) \
        .option("inferSchema", True) \
        .csv(path)

    # Row count
    row_count = df.count()
    log(f"Row count: {row_count:,}")

    # Schema
    log("\nSchema:")
    df.printSchema()

    # Null counts per column
    from pyspark.sql.functions import col, count, when, isnan

    log("\nNull counts per column:")
    null_counts = df.select([
        count(when(col(c).isNull(), c)).alias(c)
        for c in df.columns
    ])
    null_counts.show(truncate=False)

    # Sample rows
    log("\nSample rows (up to 5):")
    df.show(5, truncate=False)

    log("")

log(separator)
log("PROFILING COMPLETE")
log(f"Inspected: {', '.join(FILES_TO_INSPECT)}")
log(separator)

# Write report to docs/dataset_dictionary.md (basic version)
docs_dir = "docs"
os.makedirs(docs_dir, exist_ok=True)
report_path = os.path.join(docs_dir, "dataset_dictionary.md")

with open(report_path, "w", encoding="utf-8") as f:
    f.write("# HealthInsight Dataset Dictionary\n\n")
    f.write("> Auto-generated by `spark/01_profile_dataset.py`.\n")
    f.write("> All records are synthetic — generated by Synthea.\n\n")
    f.write("\n".join(report_lines))

print(f"\nReport written to: {report_path}")
print("NEXT STEP: Review the report and confirm which columns exist before writing transformations.")

spark.stop()
